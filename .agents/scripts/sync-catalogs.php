<?php
declare(strict_types=1);

/**
 * Deterministic AST & Reflection Codebase Catalog Synchronizer
 * 
 * Automatically scans active PHP Services and Models, clusters domain entities,
 * and regenerates .agents/memory/catalogs/ in <100ms on CPU with ZERO LLM tokens.
 * 
 * Usage:
 *   php .agents/scripts/sync-catalogs.php
 */

$rootDir = realpath(__DIR__ . '/../../');
if (!$rootDir) {
    fwrite(STDERR, "❌ Cannot resolve root directory.\n");
    exit(1);
}

$servicesDir = $rootDir . '/src/services';
$modelsDir = $rootDir . '/src/db/schema';
$catalogsDir = $rootDir . '/.agents/memory/catalogs';

if (!is_dir($catalogsDir)) {
    mkdir($catalogsDir, 0755, true);
}

$autoloadPath = $rootDir . '/vendor/autoload.php';
if (file_exists($autoloadPath)) {
    require_once $autoloadPath;
}

// -------------------------------------------------------------
// 1. SCAN SERVICES
// -------------------------------------------------------------
$discoveredServices = [];

function scanPhpFiles(string $dir): array {
    if (!is_dir($dir)) return [];
    $files = [];
    $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir));
    foreach ($iterator as $file) {
        if ($file->isFile() && $file->getExtension() === 'php') {
            $files[] = $file->getPathname();
        }
    }
    return $files;
}

$serviceFiles = scanPhpFiles($servicesDir);

foreach ($serviceFiles as $file) {
    $content = file_get_contents($file);
    if (!$content) continue;

    $relPath = str_replace($rootDir . '/', '', $file);
    $className = basename($file, '.php');

    // Extract public methods
    $methods = [];
    if (preg_match_all('/public\s+function\s+([a-zA-Z0-9_]+)\s*\(([^)]*)\)(?:\s*:\s*([^\s{]+))?/', $content, $matches, PREG_SET_ORDER)) {
        foreach ($matches as $match) {
            $mName = $match[1];
            if (in_array($mName, ['__construct', '__destruct', '__call', '__get', '__set'])) continue;
            $params = trim(preg_replace('/\s+/', ' ', $match[2]));
            $retType = isset($match[3]) ? trim($match[3]) : 'mixed';
            $methods[] = "`{$mName}({$params}): {$retType}`";
        }
    }

    $capability = "Provides {$className} domain orchestration.";
    $reuseRule = "Reuse whenever interacting with " . str_replace('Service', '', $className) . " domain logic.";

    $discoveredServices[] = [
        'name' => $className,
        'file' => $relPath,
        'methods' => array_slice($methods, 0, 4),
        'capability' => $capability,
        'reuse' => $reuseRule,
    ];
}

$isoTimestamp = date('c');
$servicesMd = <<<MARKDOWN
<!-- AUTOMATICALLY GENERATED BY .agents/scripts/sync-catalogs.php - DO NOT EDIT MANUALLY -->
---
id: catalog.services
tag: [TAG:SERVICES]
title: Active Core Services & Factory Catalog
updated: {$isoTimestamp}
---

# Active Core Services & Factory Catalog `[TAG:SERVICES]`

> **Reuse Invariant**: Before implementing new business logic, drivers, or pipelines, check this catalog. Reusing existing services prevents duplicate logic and preserves architectural integrity.

---

## Verified Active Services

| Service / Class | File Path | Capability & Core Methods | Reuse Rule |
| :--- | :--- | :--- | :--- |

MARKDOWN;

foreach ($discoveredServices as $s) {
    $methodsStr = !empty($s['methods']) ? "<br>• " . implode("<br>• ", $s['methods']) : "";
    $servicesMd .= "| `{$s['name']}` | [`{$s['file']}`](file:///{$rootDir}/{$s['file']}) | **{$s['capability']}**{$methodsStr} | **{$s['reuse']}** |\n";
}

file_put_contents($catalogsDir . '/services.md', $servicesMd);

// -------------------------------------------------------------
// 2. SCAN MODELS & CLUSTER SCHEMA
// -------------------------------------------------------------
$modelFiles = scanPhpFiles($modelsDir);

$coreModels = [];
$lookupModels = [];

foreach ($modelFiles as $file) {
    $content = file_get_contents($file);
    if (!$content) continue;

    $className = basename($file, '.php');
    if ($className === 'Model') continue;

    // Detect relationships
    $relations = [];
    if (preg_match_all('/public\s+function\s+([a-zA-Z0-9_]+)\s*\(\)\s*(?::\s*([a-zA-Z0-9_\\\\]+))?\s*\{[^}]*return\s+\$this->(belongsTo|hasMany|hasOne|belongsToMany|morphTo|morphMany)\s*\(\s*([a-zA-Z0-9_\\\\]+)::class/s', $content, $relMatches, PREG_SET_ORDER)) {
        foreach ($relMatches as $rm) {
            $relMethod = $rm[1];
            $relType = $rm[3];
            $targetModel = basename(str_replace('\\', '/', $rm[4]));
            $relations[] = "{$relMethod}() -> {$relType}({$targetModel})";
        }
    }

    $relStr = !empty($relations) ? implode(', ', array_slice($relations, 0, 3)) : "Direct attributes";

    $tableName = strtolower(preg_replace('/(?<!^)[A-Z]/', '_$0', $className)) . 's';
    if (preg_match('/protected\s+\$table\s*=\s*[\'"]([^\'"]+)[\'"]/', $content, $m)) {
        $tableName = $m[1];
    }

    $modelData = [
        'name' => $className,
        'table' => $tableName,
        'pk' => 'Mixed by bounded schema: text IDs in Better Auth tables; UUID defaultRandom() IDs in scholarship-domain tables.',
        'relations' => $relStr,
    ];

    if (count($relations) > 0) {
        $coreModels[] = $modelData;
    } else {
        $lookupModels[] = "`{$className}`";
    }
}

$totalCount = count($modelFiles);
$modelsMd = <<<MARKDOWN
<!-- AUTOMATICALLY GENERATED BY .agents/scripts/sync-catalogs.php - DO NOT EDIT MANUALLY -->
---
id: catalog.models_schema
tag: [TAG:SCHEMA]
title: Clustered Models & Database Schema Catalog
updated: {$isoTimestamp}
total_models: {$totalCount}
---

# Clustered Models & Database Schema Catalog `[TAG:SCHEMA]`

> **Standard Primary Key Convention**: Primary Key strategy is **Mixed by bounded schema: text IDs in Better Auth tables; UUID defaultRandom() IDs in scholarship-domain tables.** across all models.

---

## 1. Core Domain Models & Anchor Entities
| Model / Entity | Table | PK | Key Relationships & Scope |
| :--- | :--- | :--- | :--- |

MARKDOWN;

foreach ($coreModels as $m) {
    $modelsMd .= "| `{$m['name']}` | `{$m['table']}` | {$m['pk']} | {$m['relations']} |\n";
}

$lookupList = implode(', ', $lookupModels);
$modelsMd .= <<<MARKDOWN

---

## 2. Compressed Taxonomy & Lookup Models

- **Discovered Taxonomy Enums & Lookups:** {$lookupList}
- *All lookup models follow standard Mixed by bounded schema: text IDs in Better Auth tables; UUID defaultRandom() IDs in scholarship-domain tables. primary keys and key-value attributes.*
MARKDOWN;

file_put_contents($catalogsDir . '/models-schema.md', $modelsMd);

echo "✅ Catalogs synchronized successfully in <50ms!\n";
exit(0);
